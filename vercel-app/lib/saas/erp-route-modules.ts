export function resolveApiPathSaasModule(pathname: string): SaasModuleKey | null {
  const p = pathname.split("?")[0] || ""
  for (const ex of SAAS_API_GATE_EXEMPT_PREFIXES) {
    if (p === ex || p.startsWith(ex)) return null
  }
  const sorted = [...API_PATH_RULES].sort((a, b) => b.prefix.length - a.prefix.length)
  for (const rule of sorted) {
    if (p.startsWith(rule.prefix)) return rule.module
  }
  return null
}

export function isSaasGatedAdminHref(href: string): boolean {
  return resolveAdminPathSaasModule(href) != null
}

function normalizeAdminPath(pathname: string): string {
  const raw = String(pathname || "").trim()
  if (!raw) return ""
  const base = raw.split("?")[0] || ""
  if (base.length > 1 && base.endsWith("/")) return base.slice(0, -1)
  return base
}
