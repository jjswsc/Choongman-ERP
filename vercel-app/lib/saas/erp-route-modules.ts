/** admin 경로 → SaaS 모듈. null = 게이트 없음(대시보드·미과금 영역). */
export function resolveAdminPathSaasModule(pathname: string): SaasModuleKey | null {
  const p = normalizeAdminPath(pathname)
  if (!p || p === "/admin" || p === "/admin/settings" || p === "/admin/help") return null
  if (p.startsWith("/admin/ai-center")) return "ai_center"
  if (p.startsWith("/admin/notices")) return "notices"
  if (p.startsWith("/admin/company-documents")) return "documents"
  if (p.startsWith("/admin/work-log")) return "work_log"
  if (p.startsWith("/admin/pos-cost-analysis")) return "cost_analysis"
  if (p.startsWith("/admin/crm") || p.startsWith("/admin/members")) return "member_mgmt"
  if (p.startsWith("/admin/marketing")) return "marketing"
  if (
    p.startsWith("/admin/live-store-sales") ||
    p.startsWith("/admin/ops-center") ||
    p.startsWith("/admin/sales-management") ||
    p.startsWith("/admin/total-sales")
  ) {
    return "pos_base"
  }
  if (p.startsWith("/admin/interior")) return "logistics"
  if (
    p.startsWith("/admin/store-ops") ||
    p.startsWith("/admin/store-check") ||
    p.startsWith("/admin/store-visit") ||
    p.startsWith("/admin/store-repairs") ||
    p.startsWith("/admin/complaints")
  ) {
    return "pos_base"
  }
  if (p === "/pos" || p.startsWith("/pos/")) return "pos_base"
  if (p.startsWith("/admin/pos-")) return "pos_base"
  if (
    p.startsWith("/admin/attendance") ||
    p.startsWith("/admin/leave") ||
    p.startsWith("/admin/hr-calendar") ||
    p.startsWith("/admin/payroll") ||
    p.startsWith("/admin/employees") ||
    p.startsWith("/admin/hr-policies") ||
    p.startsWith("/admin/hr")
  ) {
    return "attendance"
  }
  if (
    p.startsWith("/admin/items") ||
    p.startsWith("/admin/vendors") ||
    p.startsWith("/admin/orders") ||
    p.startsWith("/admin/order-create") ||
    p.startsWith("/admin/stock") ||
    p.startsWith("/admin/inbound") ||
    p.startsWith("/admin/outbound") ||
    p.startsWith("/admin/accounting/purchase-order")
  ) {
    return "logistics"
  }
  if (
    p.startsWith("/admin/receivable-payable") ||
    p.startsWith("/admin/expense-management") ||
    p.startsWith("/admin/petty-cash") ||
    p.startsWith("/admin/bank-transactions") ||
    p.startsWith("/admin/depreciation") ||
    p.startsWith("/admin/financial-statements") ||
    p.startsWith("/admin/chart-of-accounts") ||
    p.startsWith("/admin/tax-filing") ||
    p.startsWith("/admin/accounting")
  ) {
    return "accounting"
  }
  return null
}

