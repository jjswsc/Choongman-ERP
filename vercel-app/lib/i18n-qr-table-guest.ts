export function qrGuestT(lang: string, key: string): string {
  const L: QrGuestLang = lang === 'ko' || lang === 'en' ? lang : 'th'
  return DICT[L][key] || DICT.en[key] || key
}

export function normalizeQrGuestLang(raw: string | null | undefined): QrGuestLang {
  const s = String(raw || '').trim().toLowerCase()
  if (s === 'ko' || s === 'en' || s === 'th') return s
  return 'th'
}
