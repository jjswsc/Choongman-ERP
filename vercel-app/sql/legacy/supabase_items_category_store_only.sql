-- ============================================================
-- 카테고리 "매장 전용" → "Store Only" (영어) 변경
-- 품목 관리 카테고리 검색에서 영어 표기로 통일
-- 사용법: Supabase 대시보드 > SQL Editor > 붙여넣기 > Run
-- ============================================================

UPDATE items
SET category = 'Store Only'
WHERE category = '매장 전용';
