SELECT
  'RPKM2026',
  'RPKM2026',
  coalesce(nullif(btrim(c.name), ''), 'RPKM2026'),
  'Chulalongkorn student cash coupon 200 THB',
  true,
  coalesce(c.valid_from, date '2026-07-23'),
  coalesce(c.valid_to, date '2026-10-31'),
  null,
  1,
  0
FROM public.pos_coupons c
WHERE upper(trim(c.code)) = 'RPKM2026'
  AND NOT EXISTS (
    SELECT 1
    FROM public.member_coupon_promo_codes p
    WHERE upper(trim(p.code)) = 'RPKM2026'
      AND coalesce(p.tenant_id, '') = ''
  );

-- 2) 이미 있으면 활성·기간만 맞춤
