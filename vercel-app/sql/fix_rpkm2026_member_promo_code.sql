SET
  coupon_code = 'RPKM2026',
  is_active = true,
  valid_from = coalesce(c.valid_from, p.valid_from, date '2026-07-23'),
  valid_to = coalesce(c.valid_to, p.valid_to, date '2026-10-31'),
  label = coalesce(nullif(btrim(p.label), ''), nullif(btrim(c.name), ''), 'RPKM2026'),
  updated_at = (now() at time zone 'Asia/Bangkok')
FROM public.pos_coupons AS c
WHERE upper(trim(p.code)) = 'RPKM2026'
  AND upper(trim(c.code)) = 'RPKM2026';

