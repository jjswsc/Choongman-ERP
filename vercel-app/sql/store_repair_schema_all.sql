-- 매장 수리 신고 + 진행 로그 (한 번에 실행)
-- Storage: 버킷 store-repair-photos — store_repair_photos_storage_bucket.sql 또는 앱 presign 자동 생성

-- 1) 티켓 테이블 (먼저 필요)
CREATE TABLE IF NOT EXISTS store_repair_tickets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_number text NOT NULL,
  store_name text NOT NULL,
  reporter text,
  category text,
  priority text,
  area text,
  title text,
  description text,
  photo_urls jsonb NOT NULL DEFAULT '[]'::jsonb,
  status text NOT NULL DEFAULT '접수',
  handler text,
  reported_at timestamptz NOT NULL DEFAULT now(),
  started_at timestamptz,
  completed_at timestamptz,
  resolution_note text,
  vendor_name text,
  estimated_cost numeric,
  actual_cost numeric
);

CREATE INDEX IF NOT EXISTS idx_store_repair_tickets_store ON store_repair_tickets (store_name);
CREATE INDEX IF NOT EXISTS idx_store_repair_tickets_status ON store_repair_tickets (status);
CREATE INDEX IF NOT EXISTS idx_store_repair_tickets_reported ON store_repair_tickets (reported_at DESC);

COMMENT ON TABLE store_repair_tickets IS '매장 시설 수리·수선 신고';

-- 2) 진행 타임라인 (티켓 테이블 생성 후에만 성공)
CREATE TABLE IF NOT EXISTS store_repair_progress_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id bigint NOT NULL REFERENCES store_repair_tickets(id) ON DELETE CASCADE,
  author text,
  note text NOT NULL DEFAULT '',
  photo_urls jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_store_repair_progress_ticket ON store_repair_progress_logs (ticket_id, created_at DESC);

COMMENT ON TABLE store_repair_progress_logs IS '매장 수리 신고 진행 타임라인';
